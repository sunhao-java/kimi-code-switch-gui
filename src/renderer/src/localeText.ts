export function toTraditionalChinese(value: string): string {
  let result = value;
  for (const [source, target] of TRADITIONAL_PHRASES) {
    result = result.split(source).join(target);
  }
  return result
    .split("")
    .map((char) => TRADITIONAL_CHARS[char] ?? char)
    .join("");
}
